//! Методы алгоритма Якоби

use nalgebra::DMatrix;

/// Вычисляет косинус и синус угла поворота Гивенса
///
/// Угол подбирается такой, чтобы при применении соответствующего поворота
/// к матрице A элемент Apq занулился
///
/// # Аргументы
///
/// * `a_pp` - диагональный элемент App
/// * `a_qq` - диагональный элемент Aqq
/// * `a_pq` - внедиагональный элемент для зануления Apq
///
/// # Возвращаемые значения
///
/// * `Some((cos, sin))` - если Apq не нуль. Гарантируется `cos > 0`
///   и `|fi| < pi/4` для взятия меньшего корня для тангенса для лучшей сходимости
/// * `None` - если `Apq == 0` => поворот не нужен
///
pub(crate) fn rotation_cos_sin(a_pp: f32, a_qq: f32, a_pq: f32) -> Option<(f32, f32)> {
    if a_pq == 0.0 {
        return None;
    }
    let c = (a_qq - a_pp) / (2.0 * a_pq);
    let root = (c * c + 1.0).sqrt();
    let t = if c > 0.0 { 1.0 / (c + root) } else { 1.0 / (c - root) };
    let cos = 1.0 / (1.0 + t * t).sqrt();
    let sin = t * cos;
    Some((cos, sin))
}

/// Выполняется шаг Якоби: зануление Apq и обновление связанных элементов
///
/// Так как матрица A симметрична, то все зеркальные элементы обновляются тоже (ij = ji)
///
/// # Аргументы
///
/// * `a` - матрица, которая изменяется в методе
/// * `p`, `q` - индексы зануляемого недиагонального элемента
/// * `t` - тангенс угла поворота, `t == sin / cos`,
/// * `cos`, `sin` - косинус и синус угла поворота, полученные из `rotation_cos_sin(...)`
///
/// # Возвращаемое значение
///
/// f32 - Квадрат старого значения Apq для обновления суммы `S`
///
/// # Паника
///
/// Метод паникует, если `p == q` (попытка обновить диагональные элементы),
/// или при выходе за границы матрицы (поведение `DMatrix`)
///
pub(crate) fn rotate_a(
    a: &mut DMatrix<f32>,
    p: usize,
    q: usize,
    t: f32,
    cos: f32,
    sin: f32,
) -> f32 {

    assert_ne!(p, q, "индекс столбца не должен быть равен индексу строки");

    let a_pp: f32 = a[(p, p)];
    let a_qq: f32 = a[(q, q)];
    let a_pq: f32 = a[(p, q)];

    a[(p, p)] = a_pp - a_pq * t;
    a[(q, q)] = a_qq + a_pq * t;

    let fraction = sin / (1.0 + cos);
    for r in 0..a.nrows() {
        if r != q && r != p {
            let a_rp = a[(r, p)];
            a[(r, p)] = a_rp - sin * (a[(r, q)] + fraction * a_rp);
            a[(r, q)] = a[(r, q)] + sin * (a_rp - fraction * a[(r, q)]);
            a[(p, r)] = a[(r, p)];
            a[(q, r)] = a[(r, q)];
        }
    }

    a[(p, q)] = 0.0;
    a[(q, p)] = 0.0;

    a_pq.powi(2)
}

/// Обновляет матрицу собственных векторов `V` после шага Якоби,
/// которая будет являться произведением всех промежуточных матриц поворотов,
/// при этом будут меняться только отдельные элементы матрицы для эффективности
///
/// # Аргументы
///
/// * `v` - матрица собственных векторов, первоначально является единичной
/// * `p`, `q` - индексы зануляемого недиагонального элемента
/// * `cos`, `sin` - косинус и синус угла поворота, полученные из `rotation_cos_sin(...)`
///
pub(crate) fn rotate_v(v: &mut DMatrix<f32>, p: usize, q: usize, cos: f32, sin: f32) {

    for r in 0..v.nrows() {
        let v_rp = v[(r, p)];
        v[(r, p)] = v_rp * cos - v[(r, q)] * sin;
        v[(r, q)] = v_rp * sin + v[(r, q)] * cos;
    }

}

/// Сумма квадратов недиагональных элементов матрицы A
///
/// Соответствует величине `S`. Считается только по верхнему треугольнику (`q > p`),
/// так как у нас симметричная матрица
///
/// # Аргументы
///
/// * `a` - симметричная матрица, которая изменяется в методе
///
/// # Возвращаемое значение
///
/// f32 - сумма квадратов недиагональных элементов
///
pub fn off_sum(a: &DMatrix<f32>) -> f32 {
    let mut off_sum = 0.0;
    let n  = a.nrows();

    for p in 0..n - 1 {
        for q in p + 1..n {
            off_sum += a[(p, q)] * a[(p, q)];
        }
    }

    off_sum
}
